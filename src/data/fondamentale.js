// De Mauro's *vocabolario di base* — the words that make Italian readable.
//
// Why a curated list and not a scraped frequency dump: the generation
// experiment in research/gen-experiment built exactly that dump, from
// subtitles, and it came back with junk lemmas and — worse — no `tavolo`, no
// `letto`, no `sedia` and no `porta` anywhere in its top 3,000. Corpora
// under-represent the objects in front of you because nobody says "table" out
// loud. De Mauro solved this in 1980 by splitting the base vocabulary into
// tiers: *fondamentale* (the ~2,000 most frequent), *alto uso*, and *alta
// disponibilità* — the words everyone knows and nobody writes down. This list
// is the fondamentale tier in frequency order with the alta disponibilità
// concrete nouns folded in at the point a learner needs them, which is what
// makes it a teaching list rather than a corpus artefact.
//
// Honest about the ranks: these are this app's ordering, an approximation of
// the published frequency order rather than a transcription of it. Nothing
// downstream depends on a word sitting at exactly its De Mauro rank — the
// coverage weighting in shared/coverage.js needs the *shape* of the
// distribution, not a specific word's place in it — but don't cite a number
// from here as if it were De Mauro's own.
//
// TARGET is 2,000. The first 300 are seeded here, accurately, in rank order;
// appending the rest is mechanical — add entries to the end of the array and
// the ranks stay contiguous, which fondamentale.test.js checks.
//
// Storing nouns:
//   A noun whose ending gives its gender away is stored bare — `tavolo` is
//   masculine because it ends in -o, `sedia` is feminine because it ends in
//   -a, and an article would just be noise.
//   A noun whose ending does *not* give its gender away is stored with its
//   definite article, as the design requires: `la chiave`, never `chiave`.
//   That covers every noun in -e, every accented final (`la città`), every
//   plural-only word (`i soldi`), and the nouns whose ending actively lies —
//   `la mano` is feminine, `il problema` is masculine.
//
// One known limit, and it bit at rank 352: for a vowel-initial opaque noun
// the article elides to `l'` and stops carrying the gender on its own
// (`l'amore`, `l'arte`). Those entries carry a real `gender` field —
// `"m"` or `"f"` — instead of leaning on the convention, and it is required
// exactly there: every entry whose `it` starts with `l'` has one, and no
// other entry does. fondamentale.test.js checks both directions.
//
// Glosses are English *and* Polish because the learner is a Polish native who
// also speaks English, and the two languages carve meaning differently often
// enough to be worth showing both. Multiple senses are separated with " · ".

export const FONDAMENTALE_TARGET = 2000;

// ── The fasce ────────────────────────────────────────────────────────────
// La Riserva draws the reservoir in bands of 200 — "Fascia 3 · posti
// 401–600" — and PLAN.md settles that a *fascia* is the door: the grid is
// deliberately not two thousand buttons, so a band is what opens.
//
// This lives here rather than in shared/coverage.js, where BAND_SIZE used to
// sit, because it is now two things at once. It was a way of slicing the
// coverage arithmetic; it is also the container the base vocabulary is
// *studied* in, which is what shared/stats.js enumerates a Riserva unit from.
// stats.js cannot take it from coverage.js — coverage.js imports MODULE_STATS
// back out of stats.js, and the cycle would leave one of the two reading an
// uninitialised binding — so the shape of the reservoir sits with the
// reservoir.
//
// `label` is English on purpose. It is what La Piazza prints above a due item,
// in a line of English prose that marks no spans, so an Italian "Fascia 3"
// there would be unmarked Italian (WCAG 3.1.2). It states the same fact La
// Riserva's own Italian heading states, and that heading is built on the
// screen where it can carry `lang="it"` — which a11y.test.jsx now asserts
// against the DOM ("marks the fascia heading and the drill's posto in La
// Riserva"), because for one commit it did not: the heading's <Eyebrow>
// swallowed the prop, and this paragraph was resting on a tag that had never
// been rendered.
export const BAND_SIZE = 200;

