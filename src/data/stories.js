// brings in the passato remoto, the passive and the impersonal si — one C1
// reader is literary narration, the other is journalistic reportage, since
// register is as much of a C1 skill as tense is.
//
// From B2 up, the comprehension questions and their explanations are in
// Italian (as they already are at B1) — at that level reading the question
// is part of the exercise.
